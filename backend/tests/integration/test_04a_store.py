def run(coro):
    return asyncio.run(coro)


def unit_vector(index: int, dim: int = EMBED_DIM, tilt: float = 0.0) -> list[float]:
    vec = [0.0] * dim
    vec[index] = 1.0
    if tilt:
        vec[(index + 1) % dim] = tilt
    norm = math.sqrt(sum(x * x for x in vec))
    return [x / norm for x in vec]


def make_kb(pg, project_id) -> uuid.UUID:
    kb_id = uuid.uuid4()
    pg.execute(
        "INSERT INTO knowledge_bases (id, project_id, key, name, embed_model, embed_dim,"
        " chunk_size, chunk_overlap, hybrid, rerank, rerank_model, default_top_k,"
        " normalizer_config_id, created_by) VALUES (%s, %s, %s, 'KB', 'BAAI/bge-m3', %s,"
        " 400, 0, true, true, 'BAAI/bge-reranker-v2-m3', 5, 'format-v1', 'test')",
        (kb_id, project_id, f"kb-{kb_id.hex[:8]}", EMBED_DIM),
    )
    return kb_id


async def _kb(session, kb_id) -> KnowledgeBase:
    return await session.get(KnowledgeBase, kb_id)


async def add_document(kb_id, filename, sha, acl_roles=(), acl_users=(), chunks=()):
    async with db.session_scope() as session:
        store = PgKnowledgeStore(session)
        kb = await _kb(session, kb_id)
        document, outcome = await store.register_upload(
            kb,
            filename=filename,
            sha256=sha,
            size=10,
            raw_path=f"raw/{filename}",
            acl_roles=list(acl_roles),
            acl_users=list(acl_users),
            created_by="test",
        )
        document.status = "indexed"  # search reads indexed only (r1 MAJOR-3)
        rows = await store.replace_chunks(
            document,
            [NewChunk(ordinal=i, text=t, breadcrumb="KB › Doc", token_count=3) for i, t in chunks],
            "BAAI/bge-m3",
        )
        await session.commit()
        return document.id, outcome, document.version, [r.id for r in rows]


def test_04a_schema_chunks_embedding_has_installation_dimension(pg):
    (typmod,) = pg.execute(
        "SELECT atttypmod FROM pg_attribute WHERE attrelid = 'chunks'::regclass"
        " AND attname = 'embedding'"
    ).fetchone()
    assert typmod == EMBED_DIM
    assert run(PgVectorStore().column_dim()) == EMBED_DIM


def test_04a_schema_tsv_is_generated_turkish(pg, make_project):
    kb_id = make_kb(pg, make_project())
    doc_id, *_ = run(add_document(kb_id, "a.pdf", "s1", chunks=[(0, "Fesih bildirim süreleri")]))
    (tsv,) = pg.execute("SELECT tsv::text FROM chunks WHERE document_id = %s", (doc_id,)).fetchone()
    assert "fesih" in tsv  # stemmed by the turkish configuration, generated by Postgres


