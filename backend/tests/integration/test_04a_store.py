def test_04a_upsert_without_chunk_row_fails_loud(pg, make_project):
    from ffcore.knowledge.vectorstore.base import VectorStoreError

    kb_id = make_kb(pg, make_project())
    record = VectorRecord(
        chunk_id=uuid.uuid4(), kb_id=kb_id, document_id=uuid.uuid4(), dense=unit_vector(1)
    )
    with pytest.raises(VectorStoreError) as err:
        run(PgVectorStore().upsert([record]))
    assert err.value.code == "chunk_not_found"
