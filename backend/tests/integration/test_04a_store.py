def test_04a_4_reupload_same_file_keeps_record_and_bumps_version(pg, make_project):
    kb_id = make_kb(pg, make_project())
    first, outcome1, v1, _ = run(add_document(kb_id, "a.pdf", "sha-1"))
    again, outcome2, v2, _ = run(add_document(kb_id, "a.pdf", "sha-1"))
    changed, outcome3, v3, _ = run(add_document(kb_id, "a.pdf", "sha-2"))
    assert first == again == changed
    assert (outcome1, outcome2, outcome3) == (
        UploadOutcome.created,
        UploadOutcome.unchanged,
        UploadOutcome.new_version,
    )
    assert (v1, v2, v3) == (1, 2, 3)
    (count,) = pg.execute("SELECT count(*) FROM documents WHERE kb_id = %s", (kb_id,)).fetchone()
    assert count == 1


def _index(pg, kb_id, docs):
    """docs: [(filename, acl_roles, acl_users, vector)] → {filename: chunk_id}, vectors attached."""
    records, by_name = [], {}
    for name, roles, users, vector in docs:
        doc_id, _, _, (chunk_id,) = run(
            add_document(kb_id, name, name, roles, users, chunks=[(0, f"text of {name}")])
        )
        records.append(
            VectorRecord(chunk_id=chunk_id, kb_id=kb_id, document_id=doc_id, dense=vector)
        )
        by_name[name] = chunk_id
    run(PgVectorStore().upsert(records))
    return by_name


def test_04a_3_pgvector_acl_filters_in_query(pg, make_project):
    kb_id = make_kb(pg, make_project())
    analyst_user = uuid.uuid4()
    ids = _index(
        pg,
        kb_id,
        [
            ("admin.pdf", ["admin"], [], unit_vector(0)),
            ("analyst.pdf", ["analyst"], [], unit_vector(0, tilt=0.1)),
            ("open.pdf", [], [], unit_vector(0, tilt=0.2)),
            ("personal.pdf", ["admin"], [analyst_user], unit_vector(0, tilt=0.3)),
        ],
    )
    store = PgVectorStore()
    query = VectorQuery(dense=unit_vector(0))
    as_analyst = VectorFilters(acl_roles=("analyst",), acl_users=(str(analyst_user),))
    analyst_hits = {h.chunk_id for h in run(store.search(kb_id, query, as_analyst, top_k=10))}
    admin_hits = {
        h.chunk_id for h in run(store.search(kb_id, query, VectorFilters(acl_roles=("admin",)), 10))
    }
    assert analyst_hits == {ids["analyst.pdf"], ids["open.pdf"], ids["personal.pdf"]}
    assert ids["admin.pdf"] in admin_hits and ids["analyst.pdf"] not in admin_hits


def test_04a_16_empty_acl_open_inside_kb_only(pg, make_project):
    kb_a = make_kb(pg, make_project())
    kb_b = make_kb(pg, make_project())
    _index(pg, kb_a, [("open.pdf", [], [], unit_vector(5))])
    hits_a = run(
        PgVectorStore().search(
            kb_a, VectorQuery(unit_vector(5)), VectorFilters(acl_roles=("analyst",)), 5
        )
    )
    hits_b = run(
        PgVectorStore().search(
            kb_b, VectorQuery(unit_vector(5)), VectorFilters(acl_roles=("analyst",)), 5
        )
    )
    assert len(hits_a) == 1 and hits_b == []


def test_04a_pgvector_exact_and_approximate_agree_on_small_set(pg, make_project):
    kb_id = make_kb(pg, make_project())
    _index(pg, kb_id, [(f"d{i}.pdf", [], [], unit_vector(i % 7, tilt=i / 40)) for i in range(12)])
    store = PgVectorStore()
    query = unit_vector(3, tilt=0.05)
    exact = run(store.search(kb_id, VectorQuery(query, exact=True), VectorFilters(), 5))
    approx = run(store.search(kb_id, VectorQuery(query), VectorFilters(), 5))
    scores = [h.score for h in exact]
    assert len(exact) == 5 and scores == sorted(scores, reverse=True)
    assert len({h.chunk_id for h in exact} & {h.chunk_id for h in approx}) >= 4


def test_04a_10_reusable_vectors_by_text_hash_and_model(pg, make_project):
    kb_id = make_kb(pg, make_project())
    _index(pg, kb_id, [("a.pdf", [], [], unit_vector(9))])

    async def lookup(model):
        async with db.session_scope() as session:
            from ffcore.knowledge.store import text_hash

            return await PgKnowledgeStore(session).reusable_vectors(
                kb_id, [text_hash("text of a.pdf")], model
            )

    same = run(lookup("BAAI/bge-m3"))
    other = run(lookup("intfloat/multilingual-e5-large"))
    assert len(same) == 1 and other == {}


